"""Scenario loads against a real database.

The properties a scenario promises only show up live: two loads of the
same scenario hold identical rows (keys, timestamps and auth users
included), a load refuses tables that already hold rows, sequences end
up past the generated keys, and the CLI drives the same path.

Runs in a throwaway database (unique name, dropped at the end) with a
minimal `auth.users` stub, so it needs CREATEDB rights like
`test_supabase_stub_auth_users_live.py`.
"""

from __future__ import annotations

import os
import textwrap
from collections.abc import Generator
from pathlib import Path
from typing import Any
from uuid import uuid4

import pytest

from sqlproof import _database as database
from sqlproof import _dsn as conninfo
from sqlproof._dsn import quote_identifier
from sqlproof.cli import main
from sqlproof.exceptions import SqlProofScenarioError
from sqlproof.scenarios import DEFAULT_CLOCK, Scenario, ScenarioBuilder, scenario

DSN_ENV = "SQLPROOF_TEST_DATABASE_URL"

pytestmark = pytest.mark.skipif(
    DSN_ENV not in os.environ,
    reason=f"set {DSN_ENV} to run Postgres integration tests",
)

SCHEMA_SQL = """
CREATE SCHEMA auth;
CREATE TABLE auth.users (
    id uuid PRIMARY KEY,
    aud text,
    role text,
    email text NOT NULL UNIQUE
);
CREATE TABLE public.customers (
    id bigserial PRIMARY KEY,
    owner_id uuid NOT NULL REFERENCES auth.users (id),
    tier int NOT NULL CHECK (tier BETWEEN 1 AND 3),
    name text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.invoices (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES public.customers (id),
    external_ref uuid NOT NULL DEFAULT gen_random_uuid(),
    total numeric(10, 2) NOT NULL CHECK (total >= 0)
);
"""


@scenario(seed=7)
def tiered(s: ScenarioBuilder) -> None:
    alice = s.row("auth.users", name="alice")
    s.table("auth.users").fill(2)
    s.row("customers", name="acme", tier=1, owner_id=alice)
    s.table("customers").cohort(2, tier=1).cohort(3, tier=2).fill(4)
    s.table("invoices").per_parent("customers", where={"tier": 1}, count=(2, 4), default=(0, 1))


@pytest.fixture(scope="module")
def dsn() -> Generator[str]:
    base_dsn = os.environ[DSN_ENV]
    db_name = f"sqlproof_scenarios_{uuid4().hex[:12]}"
    with database.connect(base_dsn, autocommit=True) as admin:
        admin.execute(f"CREATE DATABASE {quote_identifier(db_name)}")
    try:
        parts = conninfo.conninfo_to_dict(base_dsn)
        parts["dbname"] = db_name
        db_dsn = conninfo.make_conninfo(**parts)
        with database.connect(db_dsn, autocommit=True) as connection:
            connection.execute(SCHEMA_SQL)
        yield db_dsn
    finally:
        with database.connect(base_dsn, autocommit=True) as admin:
            admin.execute(f"DROP DATABASE IF EXISTS {quote_identifier(db_name)} WITH (FORCE)")


@pytest.fixture
def empty(dsn: str) -> str:
    with database.connect(dsn, autocommit=True) as connection:
        connection.execute("TRUNCATE public.invoices, public.customers, auth.users CASCADE")
    return dsn


def _dump(dsn: str) -> dict[str, list[tuple[Any, ...]]]:
    with database.connect(dsn) as connection:
        return {
            table: connection.execute(f"SELECT * FROM {table} ORDER BY 1").fetchall()
            for table in ("auth.users", "public.customers", "public.invoices")
        }


def test_two_loads_hold_identical_rows(empty: str) -> None:
    first = tiered.load(empty)
    rows = _dump(empty)
    second = tiered.load(empty, truncate_existing=True)

    assert _dump(empty) == rows
    assert first == second
    assert first.auth_users == 3
    assert first.rows["public.customers"] == 10
    assert len(rows["public.customers"]) == 10
    assert len(rows["auth.users"]) == 3


def test_pinned_values_named_rows_and_per_parent(empty: str) -> None:
    report = tiered.load(empty)
    with database.connect(empty) as connection:
        tiers = connection.execute(
            "SELECT tier, count(*) FROM public.customers GROUP BY tier ORDER BY tier"
        ).fetchall()
        acme = connection.execute(
            "SELECT owner_id, tier FROM public.customers WHERE id = %s", [report.refs["acme"]]
        ).fetchone()
        children = connection.execute(
            "SELECT c.id, count(i.id) FROM public.customers c "
            "LEFT JOIN public.invoices i ON i.customer_id = c.id GROUP BY c.id"
        ).fetchall()
    # fill(4) draws tier freely, so only the pinned rows have exact counts.
    assert dict(tiers)[1] >= 3
    assert dict(tiers)[2] >= 3
    assert (str(acme[0]), acme[1]) == (report.refs["alice"], 1)
    # Rows are laid out in declaration order: acme, then the tier-1 cohort,
    # so ids 1-3 are the parents `where={"tier": 1}` selects.
    for customer_id, count in children:
        assert (2 <= count <= 4) if customer_id <= 3 else (count <= 1)


def test_volatile_defaults_become_reproducible(empty: str) -> None:
    tiered.load(empty)
    first = _dump(empty)
    with database.connect(empty) as connection:
        stamps = connection.execute("SELECT DISTINCT created_at FROM public.customers").fetchall()
    assert stamps == [(DEFAULT_CLOCK,)]
    tiered.load(empty, truncate_existing=True)
    # external_ref defaults to gen_random_uuid(); it must not change.
    assert _dump(empty)["public.invoices"] == first["public.invoices"]


def test_sequences_continue_past_generated_keys(empty: str) -> None:
    tiered.load(empty)
    with database.connect(empty) as connection:
        customer = connection.execute(
            "INSERT INTO public.customers (owner_id, tier, name) "
            "SELECT id, 2, 'app' FROM auth.users LIMIT 1 RETURNING id"
        ).fetchone()
        invoice = connection.execute(
            "INSERT INTO public.invoices (customer_id, total) VALUES (%s, 1) RETURNING id",
            [customer[0]],
        ).fetchone()
        max_invoice = connection.execute("SELECT max(id) FROM public.invoices").fetchone()
        connection.commit()
    assert customer[0] == 11
    assert invoice[0] == max_invoice[0]


def test_refuses_tables_that_hold_rows(empty: str) -> None:
    tiered.load(empty)
    before = _dump(empty)
    with pytest.raises(SqlProofScenarioError, match="not known to be empty"):
        tiered.load(empty)
    assert _dump(empty) == before


def test_a_failed_load_changes_nothing(empty: str) -> None:
    """auth.users and customers are written before invoices; a failure on
    invoices must roll them back too."""
    with database.connect(empty, autocommit=True) as connection:
        connection.execute(
            "CREATE FUNCTION public.reject() RETURNS trigger LANGUAGE plpgsql AS "
            "$$ BEGIN RAISE EXCEPTION 'invoices are closed'; END $$"
        )
        connection.execute(
            "CREATE TRIGGER reject BEFORE INSERT ON public.invoices "
            "FOR EACH ROW EXECUTE FUNCTION public.reject()"
        )
    try:
        with pytest.raises(Exception, match="invoices are closed"):
            tiered.load(empty)
        assert _dump(empty) == {"auth.users": [], "public.customers": [], "public.invoices": []}
    finally:
        with database.connect(empty, autocommit=True) as connection:
            connection.execute("DROP TRIGGER reject ON public.invoices")
            connection.execute("DROP FUNCTION public.reject()")


def test_cli_list_show_and_up(
    empty: str, tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    directory = tmp_path / "scenarios"
    directory.mkdir()
    (directory / "billing_scenarios.py").write_text(
        textwrap.dedent(
            """
            from sqlproof.scenarios import scenario

            @scenario(seed=3)
            def small(s):
                s.table("auth.users").fill(1)
                s.table("customers").cohort(2, tier=3)
            """
        ),
        encoding="utf-8",
    )

    assert main(["scenarios", "list", "--dir", str(directory)]) == 0
    assert "small\tseed=3" in capsys.readouterr().out

    assert main(["scenarios", "show", "small", "--dir", str(directory), "--dsn", empty]) == 0
    assert "public.customers: 2 rows" in capsys.readouterr().out

    assert main(["scenarios", "up", "small", "--dir", str(directory), "--dsn", empty]) == 0
    assert "loaded small (seed 3): 3 rows" in capsys.readouterr().out

    assert main(["scenarios", "up", "small", "--dir", str(directory), "--dsn", empty]) == 2
    assert "--truncate-existing" in capsys.readouterr().err


def test_scenario_is_importable_as_a_type() -> None:
    assert isinstance(tiered, Scenario)


def test_an_exported_scenario_loads_the_same_rows(empty: str) -> None:
    """The serialized form is the same scenario: loading the YAML export
    writes exactly what the Python definition writes."""
    from sqlproof.scenarios.serialize import dumps, load_file

    tiered.load(empty)
    expected = _dump(empty)
    with database.connect(empty, autocommit=True) as connection:
        connection.execute("TRUNCATE public.invoices, public.customers, auth.users CASCADE")

    path = Path(empty.rsplit("/", 1)[-1] + ".scenario.yaml")
    try:
        path.write_text(dumps(tiered, "yaml"), encoding="utf-8")
        load_file(path).load(empty)
    finally:
        path.unlink(missing_ok=True)
    assert _dump(empty) == expected


def test_mcp_load_scenario_loads_and_never_truncates(empty: str) -> None:
    from sqlproof.mcp.tools import load_scenario

    result = load_scenario(scenario=tiered.to_dict(), dsn=empty)
    assert result["status"] == "ok", result
    assert result["rows"]["public.customers"] == 10
    assert result["auth_users"] == 3
    loaded = _dump(empty)

    again = load_scenario(scenario=tiered.to_dict(), dsn=empty)
    assert again["status"] == "error"
    assert "never deletes rows" in again["hint"]
    assert _dump(empty) == loaded
